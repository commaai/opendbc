"""Required stock Honda RX profiles for fixture_streams._Bridge.

Select with honda_descriptors(case) for hondaNidec/hondaBosch. All messages use
Honda's four-count cycle and the DBC packer's Honda nibble checksum. POWERTRAIN_DATA
combines cruise, gas and (unless ALT_BRAKE) brake; capture its common encoder so
all three fixture entry points update the same stream. State streams run at
25 Hz and measurement streams at 50 Hz, within the stock RX watchdog limits.

Nidec ALT combines MAIN_ON with SCM_BUTTONS (no SCM_FEEDBACK stream). The
bridge must also capture _acc_state_msg as an alias of _button_msg for that
variant when updating periodic inputs; it must not add a duplicate descriptor
for the same address/bus. Deliberate counter-fault tests must inject raw frames,
rather than normalize their counters through rx_stream.

Hardware: classic Bosch uses PT bus 1 (OBD routing must expose that bus); Nidec,
radarless and CANFD use PT bus 0. CANFD variants require an FD-capable DUT and
station configured for the vehicle's nominal/data bitrates and ISO mode, even
though these required RX frames are classic-sized. Configure OBD routing and
station links before streaming; no firmware changes are required. Bosch LONG
TX tests require a stock build with ALLOW_DEBUG already enabled: production
firmware ignores BOSCH_LONG, although its required RX messages are identical.
"""
from opendbc.car.honda.values import HondaSafetyFlags
from opendbc.car.structs import CarParams
from opendbc.safety.tests.fixture_streams import _Descriptor, UnsupportedStreamProfile


def honda_descriptors(case):
  """Return descriptors without relying on attributes initialized by test setUp."""
  model = case.SAFETY_MODEL
  if model not in (CarParams.SafetyModel.hondaNidec, CarParams.SafetyModel.hondaBosch):
    raise UnsupportedStreamProfile(f'{type(case).__name__}: not a Honda safety model: {model}')

  flags = case.SAFETY_PARAM
  # Reset only fixture encoder inputs to match the newly installed neutral
  # stream. These values are never evidence of firmware state.
  case._cruise_on = False
  case._brake_pressed = False
  case._gas_pressed = False
  # COUNTER is generated by CANPacker for each of the four template frames;
  # never copy an explicit test counter into the periodic stream's payload.
  # MAIN_ON is neutral (not engaged): keep it on so the background does not
  # cancel a PCM engagement that intentionally only changes POWERTRAIN_DATA.
  descriptors = [
    _Descriptor('buttons', '_button_msg', (0, True), 25, 4, ('COUNTER',)),
    _Descriptor('speed', '_speed_msg', (0,), 50, 4, ('COUNTER',)),
    _Descriptor('powertrain', '_powertrain_data_msg', (False, False, False), 25, 4, ('COUNTER',)),
  ]
  nidec_alt = model == CarParams.SafetyModel.hondaNidec and flags & HondaSafetyFlags.NIDEC_ALT
  if not nidec_alt:
    descriptors.append(_Descriptor('main', '_acc_state_msg', (True,), 25, 4, ('COUNTER',)))
  if model == CarParams.SafetyModel.hondaNidec:
    descriptors.append(_Descriptor('stock_brake', '_rx_brake_msg', (0,), 50, 4, ('COUNTER',)))
  elif flags & HondaSafetyFlags.ALT_BRAKE:
    descriptors.append(_Descriptor('brake', '_alt_brake_msg', (False,), 25, 4, ('COUNTER',)))
  return descriptors
