"""Required RX profiles for the angle/curvature safety fixtures.

Rates are bounded at 25 Hz for state and 50 Hz for measurements. Even the
100 Hz firmware checks receive a frame within their ten-period watchdog bound.
Counter cycles and checksums are generated by the fixture's DBC CANPacker.
"""
from opendbc.car.structs import CarParams
from opendbc.safety.tests.fixture_streams import _Descriptor


def _message(message, bus, values, capture_method, fix_checksum=None):
  """Supply a neutral message missing from a fixture's encoder API.

  _Bridge uses the callable name to wrap a real fixture method for recording.
  This does not add methods to, or otherwise modify, the fixture class.
  """
  def encode(case):
    return case.packer.make_can_msg_safety(message, bus, values, fix_checksum=fix_checksum)
  encode.__name__ = capture_method
  return encode


def _leaf_brake_length(frame):
  # nissan.h requires 0x1cc length 4; the Leaf DBC describes eight bytes.
  address, data, bus = frame
  return address, data[:4], bus


def get_descriptors(case):
  """Return every required RX group for a supported mode, otherwise None.

  Bus and DBC differences come from the concrete fixture (Nissan alternate EPS
  and Leaf, Ford CAN/CAN FD, Tesla stock/longitudinal, MEB original/2024 CRC).
  Ignition-only silent-mode fixtures are intentionally owned by the parent.
  """
  model = case.SAFETY_MODEL
  if model == CarParams.SafetyModel.ford:
    return [
      _Descriptor('speed', '_speed_msg', (0,), 50, 16, ('VehVActlBrk_No_Cnt',)),
      _Descriptor('speed_2', '_speed_msg_2', (0,), 50, 16, ('VehVActlEng_No_Cnt',)),
      _Descriptor('yaw', '_yaw_rate_msg', (0, 0), 50, 256, ('VehRollYaw_No_Cnt',)),
      _Descriptor('pcm', '_pcm_status_msg', (False,), 25),
      _Descriptor('gas', '_user_gas_msg', (0,), 25),
      _Descriptor('moving', '_vehicle_moving_msg', (0,), 25),
    ]
  if model == CarParams.SafetyModel.tesla:
    # Avoid command builders during template construction: steering builders
    # advance time and depend on runtime dictionaries initialized after setUp.
    camera_long = _message('DAS_control', 2, {}, '_long_control_msg')
    camera_angle = _message('DAS_steeringControl', 2, {'DAS_steeringControlType': 0}, '_angle_cmd_msg')
    ui = _message('UI_warning', 0, {'buckleStatus': 1}, '_pcm_status_msg')
    return [
      _Descriptor('camera_long', camera_long, (), 25, 8, ('DAS_controlCounter',)),
      _Descriptor('camera_angle', camera_angle, (), 50, 16, ('DAS_steeringControlCounter',)),
      _Descriptor('speed', '_speed_msg', (0,), 50, 16, ('DI_speedCounter',)),
      _Descriptor('speed_2', '_speed_msg_2', (0,), 50, 16, ('ESP_wheelRotationCounter',)),
      _Descriptor('angle', '_angle_meas_msg', (0,), 50, 16, ('EPAS3S_sysStatusCounter',)),
      _Descriptor('gas', '_user_gas_msg', (0,), 25, 16, ('DI_systemStatusCounter',)),
      _Descriptor('brake', '_user_brake_msg', (False,), 25, 16, ('ESP_statusCounter',)),
      _Descriptor('pcm', '_pcm_status_msg', (False,), 25, 16, ('DI_locStatusCounter',)),
      _Descriptor('ui', ui, (), 25, 16, ('UI_warningCounter',)),
    ]
  if model == CarParams.SafetyModel.nissan:
    descriptors = [
      _Descriptor('angle', '_angle_meas_msg', (0,), 50, 16, ('COUNTER',)),
      _Descriptor('speed', '_speed_msg', (0,), 50),
      _Descriptor('pcm', '_pcm_status_msg', (False,), 25),
      _Descriptor('gas', '_user_gas_msg', (0,), 25),
    ]
    if case.DBC == 'nissan_leaf_2018_generated':
      descriptors[-1] = _Descriptor('gas', '_user_gas_msg', (0,), 25, 4, ('COUNTER',))
      brake = _message('BRAKE_PEDAL', 0, {'BRAKE_PEDAL': 0}, '_user_brake_msg', _leaf_brake_length)
      descriptors.append(_Descriptor('brake', brake, (), 25))
    else:
      descriptors.append(_Descriptor('brake', '_user_brake_msg', (False,), 25))
    return descriptors
  if model == CarParams.SafetyModel.byd:
    return [
      _Descriptor('angle', '_angle_meas_msg', (0,), 50, 16, ('COUNTER',)),
      _Descriptor('speed', '_speed_msg', (0,), 50, 16, ('COUNTER',)),
      # Both pedals share DRIVE_STATE; the bridge must also record _user_gas_msg.
      _Descriptor('pedals', '_user_brake_msg', (False,), 25),
      _Descriptor('pcm', '_pcm_status_msg', (False,), 25, 16, ('COUNTER',)),
    ]
  if model == CarParams.SafetyModel.psa:
    torque = _message('STEERING', 0, {}, '_angle_meas_msg')
    return [
      _Descriptor('pcm', '_pcm_status_msg', (False,), 25, 16, ('COUNTER',)),
      _Descriptor('speed', '_speed_msg', (0,), 50, 16, ('COUNTER',)),
      _Descriptor('angle', '_angle_meas_msg', (0,), 50),
      _Descriptor('driver_torque', torque, (), 50, 16, ('COUNTER',)),
      _Descriptor('gas', '_user_gas_msg', (0,), 25),
      _Descriptor('brake', '_user_brake_msg', (False,), 25),
    ]
  if model == CarParams.SafetyModel.volkswagenMeb:
    buttons = _message('GRA_ACC_01', 0, {}, '_button_msg')
    return [
      _Descriptor('driver_torque', '_torque_driver_msg', (0,), 50, 16, ('COUNTER',)),
      _Descriptor('brake', '_motor_14_msg', (False,), 25, 16, ('COUNTER',)),
      _Descriptor('buttons', buttons, (), 25, 16, ('COUNTER',)),
      _Descriptor('curvature', '_curvature_meas_msg', (0,), 50, 16, ('COUNTER',)),
      _Descriptor('speed_2', '_speed_msg_2', (0,), 50, 16, ('COUNTER',)),
      _Descriptor('pcm', '_tsk_status_msg', (False, False), 25, 16, ('COUNTER',)),
      _Descriptor('speed', '_speed_msg', (0,), 50, 16, ('COUNTER',)),
    ]
  return None
