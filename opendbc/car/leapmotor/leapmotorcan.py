def leapmotor_checksum(address: int, sig, d: bytearray) -> int:
  constants = LEAPMOTOR_E2E_CONSTANTS.get(address)
  if constants is None:
    return -1  # unknown message: never matches, so the frame is rejected rather than trusted
  crc = 0xFF
  for b in d[1:]:
    crc = CRC8H2F[crc ^ b]
  crc = CRC8H2F[crc ^ constants[d[1] & 0x0F]]
  return crc ^ 0xFF


# LCC_RAMP (bytes 16-17 of ADAS_LKA): 0x7801 when LCC is not steering. While stock LCC steers it moves down a ladder of
# 254 per step, one step per frame: from idle to about 31 steps when LCC starts, then deeper with more lateral
# acceleration and speed, and back to idle at once when LCC stops. The step count sets how much torque the EPS may use
# (about +/-10 early in the ramp, +/-45 at 30-31 steps, +/-70 at 42-46). Stock LCC on 3 routes (142,234 frames):
# steps = 19.1 + 9.94 * |lateral accel| + 0.112 * speed (km/h), R^2 0.83, always 25-46. With the idle word the EPS only
# applied torque to the right; with a fixed 30 steps (0x5A3D) it could not hold a curve at 75 km/h (torque flat at 61).
LCC_RAMP_IDLE = 0x7801
LCC_RAMP_STEP = 254
LCC_RAMP_STEPS_MIN = 25
LCC_RAMP_STEPS_MAX = 46


def lcc_ramp_target(lat_accel: float, v_ego_kph: float) -> int:
  """LCC_RAMP word that stock LCC would send for this lateral acceleration (m/s^2) and speed."""
  steps = round(19.1 + 9.94 * abs(lat_accel) + 0.112 * v_ego_kph)
  return LCC_RAMP_IDLE - LCC_RAMP_STEP * min(max(steps, LCC_RAMP_STEPS_MIN), LCC_RAMP_STEPS_MAX)


def lcc_ramp_next(word: int, lat_active: bool, target: int) -> int:
  """Next LCC_RAMP value: one ladder step per frame toward target while steering, straight back to idle otherwise."""
  if not lat_active:
    return LCC_RAMP_IDLE
  if word > target:
    return word - LCC_RAMP_STEP
  if word < target:
    return word + LCC_RAMP_STEP
  return word


def create_steering_control(packer, camera_lka: dict, apply_angle: float, lat_active: bool, lcc_ramp: int = LCC_RAMP_IDLE):
  """Rebuild ADAS_LKA (0x83) from the camera's latest frame, replacing only the steering fields.

  Every other field (ACC state, acceleration request, set speed, constants) is copied unchanged, so the
  stock ACC keeps working while openpilot steers. The packer recomputes the E2E checksum and runs its own
  counter, since the EPS only ever sees openpilot's frames once the camera's are blocked.
  While steering, LCC_RAMP carries lcc_ramp (see lcc_ramp_next); otherwise it is the camera's.
  """
  values = {k: v for k, v in camera_lka.items() if k not in ("CHECKSUM", "COUNTER")}
  values["STEER_ANGLE_REQ"] = apply_angle
  values["LCC_STEERING_ACTIVE_COPY"] = 1 if lat_active else 0
  if lat_active:
    values["LCC_RAMP"] = lcc_ramp
  return packer.make_can_msg("ADAS_LKA", 0, values)


STALK_PUSH_UP_CANCEL = 3

# A real ADAS_LKA frame from the camera with ACC and LCC off, used until the camera's first frame is received
ADAS_LKA_IDLE = bytes.fromhex("260500446411E100007D00700043E4000178007D000000000000000000000000")


def decode_adas_lka_idle() -> dict:
  from opendbc.can.dbc import DBC  # imported here: opendbc.can.dbc imports this module for the checksum
  msg = DBC("leapmotor_b10").addr_to_msg[0x83]
  return {name: sig.get_raw_value(ADAS_LKA_IDLE) * sig.factor + sig.offset for name, sig in msg.sigs.items()}


def create_cancel(packer, powertrain_state: dict):
  """Copy of the VCU's latest POWERTRAIN_STATE (0xB7) with the right stalk pushed up, sent to the camera (bus 2).

  The camera runs ACC and reads the stalk from this frame; pushing the stalk up cancels ACC and LCC (14 of 14 logged
  pushes ended assist within 0.25 s). The copy uses the next counter value, so it takes the place of the next real
  frame. The safety model only allows this frame with the stalk pushed up.
  """
  values = {k: v for k, v in powertrain_state.items() if k != "CHECKSUM"}
  values["STALK_PUSH"] = STALK_PUSH_UP_CANCEL
  values["COUNTER"] = (int(powertrain_state["COUNTER"]) + 1) % 16
  return packer.make_can_msg("POWERTRAIN_STATE", 2, values)
